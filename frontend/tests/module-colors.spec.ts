import {test,expect} from './fixtures';
const module=(id:string,title:string,short:string)=>({id,title,short_title:short,required_ects:5,grade:null,status:'unknown',source:null,admission:{status:'available',reason:'Offen'},semester_offered:true});
const pg=module('pg2','Programmieren 2','PG2'),se=module('se','Software Engineering','SE');
const data={import_id:null,program:'Wirtschaftsinformatik',supported:true,official_credits:5,official_grade:2.3,example_scenario:'open',unmatched_groups:[],stages:[{id:'abschnitt_1',title:'Abschnitt 1',modules:[{...module('ma1','Mathematik 1','MA1'),status:'passed',grade:'2.3'},pg,se]},{id:'abschnitt_2',title:'Abschnitt 2',modules:[{...module('db','Datenbanken','DB'),admission:{status:'unknown',reason:'Es fehlen noch 25 ECTS.'}}]}]};
test('one palette, compact two-column semester cards and removal from the overview stay synchronized',async({page})=>{
 await page.route('**/api/imports',r=>r.fulfill({json:[]}));
 await page.route('**/api/programs/wi/examples/*',r=>r.fulfill({json:data}));
 await page.goto('/?example=open');
 const passed=page.locator('[data-module-id="ma1"]'),available=page.locator('[data-module-id="pg2"]'),locked=page.locator('[data-module-id="db"]');
 await expect(passed).toHaveClass(/bg-green-50.*border-green-300/);
 await expect(available).toHaveClass(/bg-white.*border-gray-300/);
 await expect(locked).toHaveClass(/bg-gray-100/);
 const target=page.getByLabel('Module in aktuelles Semester ziehen');
 await available.dragTo(target);
 await page.locator('[data-module-id="se"]').dragTo(target);
 await expect(available).toHaveClass(/bg-blue-50/);
 const cards=target.locator('[data-planned-module]');
 await expect(cards).toHaveCount(2);
 await expect(cards.first()).toHaveClass(/bg-blue-50/);
 const a=await cards.nth(0).boundingBox(),b=await cards.nth(1).boundingBox();
 expect(Math.abs(a!.y-b!.y)).toBeLessThan(1);expect(b!.x).toBeGreaterThan(a!.x+a!.width);
 await expect(cards.first()).toContainText('PG2');
 await expect(cards.first()).not.toContainText('Programmieren 2');
 await expect(cards.first().getByRole('button',{name:'Programmieren 2 5 ECTS',exact:true})).toHaveAttribute('title','Programmieren 2');
 await available.click();
 await expect(page.getByRole('dialog').getByRole('heading',{name:'Programmieren 2',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Aus aktuellem Semester entfernen',exact:true}).click();
 await expect(target.locator('[data-planned-module="pg2"]')).toHaveCount(0);
 await expect(available).toHaveClass(/bg-white/);
 await page.reload();await expect(target.locator('[data-planned-module="pg2"]')).toHaveCount(0);
 await expect(target.locator('[data-planned-module="se"]')).toHaveClass(/bg-blue-50/);
 const legend=page.getByLabel('Kartenstatus');
 await expect(legend.getByText('Bestanden',{exact:true}).locator('span')).toHaveClass(/bg-green-50/);
 await expect(legend).not.toContainText('Fristnah');
 await page.screenshot({path:'test-results/compact-semester-colors.png',fullPage:true});
});
