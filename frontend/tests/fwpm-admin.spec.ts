import { test, expect, type Page } from '@playwright/test';
const base = {id:'wi.fwpm.date',title:'Data Engineering',short_title:'DATE',ects:5,slots:['wi.req.fwpm2','wi.req.fwpm3'],offered:true,confirmed:false,source_term:'SoSe 2026',source_url:'',pages:null,description:'Reviewed description'};
async function setup(page:Page, rows:any[]=[base], saved=false) {
 await page.route('**/api/auth/me',r=>r.fulfill({json:{id:2,role:'admin',name:'Admin'}}));
 await page.route('**/api/programs/wi/catalog',r=>r.fulfill({json:{program_id:'wi_bsc_2023',program:{name:'Wirtschaftsinformatik'},revision:'r',documents:[],fwpm_library:[{...base,terms:['SoSe 2026']},{...base,id:'wi.fwpm.winter',title:'Winter subject',short_title:'WIN',terms:['WiSe 2026/27']}],semesters:{'SoSe 2027':{status:'draft',handbook:{url:null,label:''},modules:{},...(saved?{preparation:{core_documents:[],fwpm_document:null,fwpm_courses:rows,confirmed:false}}:{})}}}}));
 await page.route('**/api/admin/programs/wi/fwpm-proposal*',r=>r.fulfill({json:{term:'SoSe 2027',source_term:'SoSe 2026',courses:rows}}));
 await page.goto('/');await page.getByRole('button',{name:'SoSe 2027 bearbeiten'}).click();await page.getByRole('button',{name:'Weiter',exact:true}).click();
 await expect(page.getByRole('button',{name:'Liste bearbeiten'})).toBeEnabled();
}
test('two lists allow shared membership, removal, creation and one PDF with fixed five credits', async ({page}) => {
 await setup(page);
 let saved:any;
 await page.route('**/api/admin/programs/wi/catalog',r=>{saved=r.request().postDataJSON();return r.fulfill({json:{revision:'saved'}});});
 await expect(page.getByText('Vorlage: SoSe 2026',{exact:false})).toBeVisible();
 await expect(page.getByLabel('FWPM ECTS')).toHaveCount(0);
 await page.getByRole('button',{name:'Liste bearbeiten'}).click();
 await page.getByRole('button',{name:'Zu FWPM 1 hinzufügen',exact:true}).click();
 await page.getByRole('button',{name:'DATE übernehmen',exact:true}).click();
 await expect(page.getByText('Data Engineering',{exact:true})).toHaveCount(2);
 await page.getByRole('button',{name:'DATE aus FWPM 2 / 3 entfernen',exact:true}).click();
 await page.getByRole('button',{name:'Zu FWPM 2 / 3 hinzufügen',exact:true}).click();
 // Opposite-season library entries are available to the administrator.
 await expect(page.getByText('WIN · Winter subject',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Neues Teilmodul erstellen'}).click();
 await page.getByLabel('FWPM Teilmodulbezeichnung').fill('New confirmed subject');
 await page.getByLabel('FWPM Kurzbezeichnung').fill('NEW');
 const pdf='/api/programs/wi/handbooks/'+'c'.repeat(64)+'.pdf';
 await page.route('**/api/admin/programs/wi/fwpm-description',r=>r.fulfill({json:{url:pdf}}));
 await page.getByLabel('FWPM Beschreibungs-PDF').setInputFiles({name:'description.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-test')});
 await expect(page.getByRole('link',{name:'Hochgeladenes PDF ansehen'})).toHaveAttribute('href',pdf);
 await page.getByRole('button',{name:'Teilmodul übernehmen',exact:true}).click();
 await page.getByRole('button',{name:'Änderungen übernehmen'}).click();
 await expect(page.getByLabel('Dieses FWPM-Angebot für SoSe 2027 bestätigen.')).not.toBeChecked();
 await page.getByRole('button',{name:'Entwurf speichern'}).click();
 const rows=saved.semesters['SoSe 2027'].preparation.fwpm_courses;
 expect(rows).toHaveLength(2);
 expect(rows.every((r:any)=>r.terms===undefined)).toBe(true);
 expect(rows.find((r:any)=>r.id===base.id).slots).toEqual(['wi.req.fwpm1']);
 expect(rows.find((r:any)=>r.id===base.id).description).toBe(base.description);
 const created=rows.find((r:any)=>r.short_title==='NEW');
 expect(created.slots).toEqual(['wi.req.fwpm2','wi.req.fwpm3']);expect(created.ects).toBe(5);expect(created.description_pdf).toBe(pdf);
 await expect(page.getByRole('heading',{name:'Semesterübersicht',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'SoSe 2027 bearbeiten'}).click();await page.getByRole('button',{name:'Weiter',exact:true}).click();
 await page.screenshot({path:'test-results/fwpm-overview.png',fullPage:true});
 await page.getByRole('button',{name:'Liste bearbeiten'}).click();
 await page.screenshot({path:'test-results/fwpm-editor.png',fullPage:true});
});
