for(const saved of [false,true]) test(`unassigned ${saved?'saved':'automatic'} candidates stay optional and do not block the offer`, async({page})=>{
 const unknown={...base,id:'wi.fwpm.optional',title:'Optional summer subject',short_title:'OPT',slots:[]};
 await setup(page,[base,unknown],saved);
 const confirm=page.getByLabel('Dieses FWPM-Angebot für SoSe 2027 bestätigen.');
 await expect(confirm).toBeEnabled();await confirm.check();
 await expect(page.getByRole('button',{name:'Weiter',exact:true})).toBeEnabled();
 await expect(page.getByText(unknown.title,{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Liste bearbeiten'}).click();
 await expect(page.getByText('Zuordnung fehlt',{exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Änderungen übernehmen'})).toBeEnabled();
 await page.getByRole('button',{name:'Zu FWPM 1 hinzufügen',exact:true}).click();
 await page.getByRole('button',{name:'OPT übernehmen',exact:true}).click();
 await page.getByRole('button',{name:'Änderungen übernehmen'}).click();
 await expect(page.getByText(unknown.title,{exact:true})).toBeVisible();
 await expect(confirm).not.toBeChecked();
 let payload:any;
 await page.route('**/api/admin/programs/wi/catalog',r=>{payload=r.request().postDataJSON();return r.fulfill({json:{revision:'saved'}});});
 await page.getByRole('button',{name:'Entwurf speichern'}).click();
 expect(payload.semesters['SoSe 2027'].preparation.fwpm_courses.find((r:any)=>r.id===unknown.id).slots).toEqual(['wi.req.fwpm1']);
});

test('unassigned PDF entries remain optional and survive applying and saving the offer',async({page})=>{
 await setup(page);
 const unknown={...base,id:'wi.fwpm.custom.pdf',title:'Optional PDF subject',short_title:'PDF',slots:[]};
 await page.route('**/api/admin/programs/wi/fwpm-pdf?*',r=>r.fulfill({json:{term:'SoSe 2027',document:{digest:'a'.repeat(64)},courses:[unknown]}}));
 await page.getByRole('button',{name:'Liste bearbeiten'}).click();
 await page.getByText('Vorschläge aus FWPM-Modulhandbuch importieren').click();
 await page.getByLabel('FWPM-PDF',{exact:true}).setInputFiles({name:'fwpm.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-test')});
 await expect(page.getByText('1 IW-Teilmodule eingelesen.',{exact:false})).toBeVisible();
 await expect(page.getByText('Zuordnung fehlt',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Änderungen übernehmen'}).click();
 await expect(page.getByLabel('Dieses FWPM-Angebot für SoSe 2027 bestätigen.')).toBeEnabled();
 await expect(page.getByText(unknown.title,{exact:true})).toHaveCount(0);
 let prepared:any;
 await page.route('**/api/admin/programs/wi/prepare',r=>{
  prepared=r.request().postDataJSON().preparation;
  return r.fulfill({json:{term:'SoSe 2027',catalog:{courses:{},pending:[],warnings:[]},modules:{},handbook:{url:null,label:''},fwpm_handbook:{url:null,label:''},core_handbooks:{}}});
 });
 await page.getByLabel('Dieses FWPM-Angebot für SoSe 2027 bestätigen.').check();
 await page.getByRole('button',{name:'Weiter',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Termine & veröffentlichen',exact:true})).toBeVisible();
 expect(prepared.fwpm_courses.find((r:any)=>r.id===unknown.id).offered).toBe(false);
 expect(prepared.fwpm_courses.find((r:any)=>r.id===unknown.id).confirmed).toBe(false);
 let payload:any;
 await page.route('**/api/admin/programs/wi/catalog',r=>{payload=r.request().postDataJSON();return r.fulfill({json:{revision:'saved'}});});
 await page.getByRole('button',{name:'Entwurf speichern'}).click();
 const optional=payload.semesters['SoSe 2027'].preparation.fwpm_courses.find((r:any)=>r.id===unknown.id);
 expect(optional.offered).toBe(false);expect(optional.confirmed).toBe(false);
 expect(optional.terms).toBeUndefined();
 await page.getByRole('button',{name:'SoSe 2027 bearbeiten'}).click();
 await page.getByRole('button',{name:'Weiter',exact:true}).click();
 await page.getByRole('button',{name:'Liste bearbeiten'}).click();
 await page.getByRole('button',{name:'Zu FWPM 2 / 3 hinzufügen',exact:true}).click();
 await page.getByRole('button',{name:'PDF übernehmen',exact:true}).click();
 await page.getByRole('button',{name:'Änderungen übernehmen'}).click();
 await expect(page.getByText(unknown.title,{exact:true})).toBeVisible();
});
