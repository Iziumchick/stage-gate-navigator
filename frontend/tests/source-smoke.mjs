// Exercise the deployed wizard and live sources without saving or publishing.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.SMOKE_URL || 'http://localhost:5173';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1920, height: 1300 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
try {
  await page.goto(base);
  await page.getByLabel('E-Mail-Adresse').fill(process.env.ADMIN_EMAIL);
  await page.getByLabel('Passwort', { exact: true }).fill(process.env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Einloggen' }).click();
  await page.getByRole('heading', { name: 'Semesterübersicht', exact: true }).waitFor();
  const before = await (await page.request.get(base + '/api/programs/wi/catalog')).json();
  if (before.semesters['WiSe 2026/27']) await page.getByRole('button',{name:'WiSe 2026/27 bearbeiten',exact:true}).click();
  else {
    await page.getByRole('button',{name:/Semester für .* erstellen/}).click();
    await page.getByLabel('Semester',{exact:true}).selectOption('WiSe 2026/27');
  }
  await page.getByRole('button', { name: 'Weiter', exact: true }).click();
  assert.equal(await page.getByRole('combobox').count(), 0);
  await page.screenshot({ path: 'test-results/live-wizard-handbook.png', fullPage: true });
  await page.getByLabel('Dieses FWPM-Angebot für WiSe 2026/27 bestätigen.').check();
  const preparationResponse = page.waitForResponse(r => r.url().endsWith('/api/admin/programs/wi/prepare'));
  await page.getByRole('button', { name: 'Weiter', exact: true }).click();
  const prepared = await (await preparationResponse).json();
  assert.ok(Object.keys(prepared.catalog.courses).length >= 33);
  assert.equal(prepared.catalog.catalog_mode, 'reviewed_code');
  assert.equal(prepared.catalog.counts.core,22);
  assert.equal(prepared.catalog.counts.pending,1);
  assert.deepEqual(prepared.catalog.pending[0].stages, ['abschnitt_1']);
  assert.deepEqual(prepared.catalog.pending.map(c => c.id), ['wi.course.enterprise_systems']);
  assert.ok(prepared.catalog.courses['wi.course.hardware']);
  assert.ok(prepared.catalog.courses['wi.course.seminar_wi']);
  assert.ok(!prepared.catalog.courses['wi.course.isc']);
  assert.equal(await page.getByLabel('ELO-Kurslink').count(), 0);
  assert.equal(await page.getByLabel('PDF-Seite von').count(), 0);
  await page.screenshot({ path: 'test-results/live-wizard-catalog.png', fullPage: true });
  assert.equal(await page.getByRole('group',{name:'Stundenplan nach Studienabschnitt'}).count(),0);
  const scheduleResponse = page.waitForResponse(r => r.url().endsWith('/api/admin/programs/wi/import/schedule'), { timeout: 70000 });
  await page.getByRole('button', { name: 'B.O.S.S.-Stundenplan abrufen' }).click();
  const schedule = await (await scheduleResponse).json();
  assert.equal(schedule.term, 'WiSe 2026/27');
  assert.equal(schedule.report.found,Object.keys(prepared.catalog.courses).length,JSON.stringify(schedule.report));
  assert.ok(Object.keys(schedule.modules).every(id => prepared.catalog.courses[id]));
  assert.ok(Object.values(schedule.modules).every(c => c.source_term === 'WiSe 2026/27'));
  assert.ok(schedule.modules['wi.course.seminar_wi'].meetings.every(m=>m.source_code==='SEM'));
  assert.deepEqual(schedule.report.unmatched,[]);
  const pj=schedule.modules['wi.course.pj'].meetings;
  assert.deepEqual([...new Set(pj.map(m=>m.source_group))].sort(),['[1]','[2]','[3]']);
  assert.ok(pj.every(m=>m.teacher_codes.length===1));
  assert.ok(pj.filter(m=>m.source_group!=='[1]').every(m=>m.room_assignment==='unresolved' && m.room==='' && m.room_candidates.length===2));
  const pjModule=page.getByTestId('schedule-module-wi.req.vertiefung_iw2');
  await pjModule.locator(':scope > summary').click();
  await pjModule.locator('details[data-course-id="wi.course.pj"] > summary').click();
  assert.equal(await pjModule.getByTestId('meeting-variant').count(),3);
  await pjModule.getByTestId('meeting-variant').nth(1).locator(':scope > summary').click();
  await page.screenshot({path:'test-results/live-project-groups.png',fullPage:true});
  const firstId = Object.keys(schedule.modules)[0];
  const group=prepared.catalog.module_groups.find(g=>g.teilmodule_ids.includes(firstId));
  await page.getByTestId(`schedule-module-${group.id}`).locator(':scope > summary').click();
  await page.screenshot({ path: 'test-results/live-wizard-sources.png', fullPage: true });
  const datesResponse = page.waitForResponse(r => r.url().endsWith('/api/admin/programs/wi/import/dates'), { timeout: 70000 });
  await page.getByRole('button', { name: 'OTH-Termine abrufen' }).click();
  const dates = await (await datesResponse).json();
  assert.equal(dates.term, 'WiSe 2026/27');
  if (dates.calendar?.lectures) assert.ok(dates.calendar.lectures.start >= '2026-10-01' && dates.calendar.lectures.end <= '2027-03-14');
  const program = await (await page.request.get(base + '/api/programs/wi/dashboard?start_term=WiSe%202026%2F27&term=WiSe%202026%2F27')).json();
  const rows = Object.fromEntries(program.stages.flatMap(s => s.modules).map(m => [m.id, m]));
  assert.equal(rows['wi.req.bwl2'].completion_rule, 'all');
  assert.equal(rows['wi.req.projektmanagement'].completion_rule, 'all');
  assert.equal(rows['wi.req.vertiefung_iw3'].completion_rule, 'one');
  assert.deepEqual(rows['wi.req.vertiefung_iw3'].details.linked_courses.map(c => c.id).sort(), ['wi.course.is', 'wi.course.isc']);
  assert.equal(rows['wi.req.bachelorarbeit'].details.composite_group.ects, 15);
  assert.equal(rows['wi.req.praktikum'].details.composite_group.ects, 26);
  assert.equal(Object.values(rows).reduce((total, m) => total + m.required_ects, 0), 210);
  const after = await (await page.request.get(base + '/api/programs/wi/catalog')).json();
  assert.equal(after.revision, before.revision);
  await page.getByRole('button', { name: 'Abmelden', exact: true }).click();
  await page.getByRole('button', { name: 'Einloggen', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log(`PASS: live wizard (${Object.keys(prepared.catalog.courses).length} code-owned courses, ${prepared.catalog.counts.fwpm} IW FWPM), BOSS ${schedule.report.found}, dates ${dates.report.status}; no save/publish or browser errors.`);
} catch (error) { await page.screenshot({ path: 'test-results/live-wizard-error.png', fullPage: true }); console.log((await page.locator('body').innerText()).slice(0, 3000)); throw error; } finally { await browser.close(); }
